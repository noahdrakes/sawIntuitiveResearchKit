    # -- trial session --------------------------------------------------------

    trial_frame = ttk.LabelFrame(root, text='pilot trial session')
    trial_frame.pack(padx=10, pady=(0, 10), fill='x')

    session = {'obj': None}

    excel_row = ttk.Frame(trial_frame)
    excel_row.pack(fill='x', padx=5, pady=(5, 0))
