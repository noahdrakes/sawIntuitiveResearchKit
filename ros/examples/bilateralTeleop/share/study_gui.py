    ttk.Entry(setup_row, textvariable=participant_var, width=8).pack(side='left', padx=(2, 15))
    ttk.Label(setup_row, text='Study:').pack(side='left')
    study_var = tk.IntVar(value=1)
    ttk.Radiobutton(setup_row, text='1 - Palpation', variable=study_var, value=1).pack(side='left')
    ttk.Radiobutton(setup_row, text='2 - Peg Transfer', variable=study_var, value=2).pack(side='left')

    status_var = tk.StringVar(value='(no session loaded)')
    ttk.Label(trial_frame, textvariable=status_var, font=('', 11, 'bold'), justify='left').pack(
        anchor='w', padx=5, pady=(0, 5))

    def refresh_status():
        obj = session['obj']
        if obj is None:
            status_var.set('(no session loaded)')
            return
        info = obj.current()
        if info is None:
            status_var.set(f'{obj.participant} / study {obj.study}: all trials complete.')
            return
        label = SETUP_INFO_LABEL[obj.study]
        setup = info['setup_info'] if info['setup_info'] is not None else 'n/a'
        mode = info['mode_code'] or '(select manually -- Warm-up)'
        done = ' [ALREADY RECORDED]' if info['done'] else ''
        status_var.set(
            f"{obj.participant} / study {obj.study}  --  trial {obj.index + 1}/{len(obj.rows)}{done}\n"
            f"trial #: {info['trial_num']}   mode: {mode}\n"
            f"{label}: {setup}\n"
            f"rosbag stem: {info['stem']}"
        )

    def apply_current_mode():
        # pushes the current trial's mode + DO policy to the robot right
        # away, so "current:" above and the robot's actual state match
        # whatever the trial panel is showing -- without this, loading a
        # session or moving to the next trial only updated the display,
        # leaving the robot on whatever mode/DO was previously active until
        # Start was clicked
        obj = session['obj']
        if obj is None:
            return
        try:
            obj.set_mode_for_current()
            refresh_mode()
        except Exception as exc:
            messagebox.showerror('Mode switch failed', str(exc))

    def load_session():
        try:
            session['obj'] = TrialSession(cmds, participant_var.get().strip(), study_var.get(),
                                           excel_path_var.get().strip(), relay, video_transport.get)
        except Exception as exc:
            messagebox.showerror('Load session failed', str(exc))
            return
        refresh_status()
        apply_current_mode()

    ttk.Button(setup_row, text='Load session', command=load_session).pack(side='left', padx=(15, 0))

    def run_async(work_fn, on_success=None, on_error=None, busy_widgets=()):
        # stop_trial()/abort_trial() send SIGINT then block waiting for
        # `ros2 bag record` to exit (now up to 30s, see _stop_process) --
        # doing that directly in a button's command callback blocks
        # Tkinter's own event loop for the whole wait, freezing the entire
        # window (this was the "GUI keeps freezing" symptom). Runs work_fn
        # on a worker thread instead and polls for completion via
        # root.after() -- Tkinter itself isn't thread-safe, so on_success/
        # on_error/re-enabling busy_widgets all happen back on the main
        # thread from that poll, never from the worker thread directly.
        for w in busy_widgets:
            w.state(['disabled'])
        result = {}

        def worker():
            try:
                result['value'] = work_fn()
            except Exception as exc:
                result['error'] = exc

        threading.Thread(target=worker, daemon=True).start()

        def poll():
            if 'value' not in result and 'error' not in result:
                root.after(150, poll)
                return
            for w in busy_widgets:
                w.state(['!disabled'])
            if 'error' in result:
                (on_error or (lambda exc: messagebox.showerror('Error', str(exc))))(result['error'])
            elif on_success:
                on_success(result.get('value'))

        root.after(150, poll)

    button_row = ttk.Frame(trial_frame)
    button_row.pack(fill='x', padx=5, pady=(0, 8))

    def start_trial():
        obj = session['obj']
        if obj is None:
            return
        try:
            path = obj.start_trial()
            # start_trial() restarts the video relay itself (fresh headers
            # per trial, see TrialSession.start_trial()) -- reflect that
            # here rather than leaving the dropdown/status showing whatever
            # was true before this trial started
            video_status.set('running' if relay.running() else 'stopped')
            transport_menu.state(['disabled'] if relay.running() else ['!disabled'])
            messagebox.showinfo('Recording', f'Recording -> {path}\n\nRun the trial, then Stop.')
            refresh_status()
        except Exception as exc:
            messagebox.showerror('Start trial failed', str(exc))

    def stop_trial():
        obj = session['obj']
        if obj is None:
            return
        status_var.set('Stopping recording, waiting for the bag to finalize -- please wait...')

        def on_success(path):
            if path:
                messagebox.showinfo('Saved', f'Saved and logged:\n{path}')
            refresh_status()

        def on_error(exc):
            messagebox.showerror('Stop trial failed', str(exc))
            refresh_status()

        run_async(obj.stop_trial, on_success, on_error, busy_widgets=trial_buttons)

    def abort_trial():
        obj = session['obj']
        if obj is None:
            return
        if not messagebox.askyesno('Abort trial', 'Stop recording and DELETE this rosbag (false start)?'):
            return
        status_var.set('Stopping recording (abort) -- please wait...')

        def on_success(_):
            refresh_status()

        def on_error(exc):
            messagebox.showerror('Abort trial failed', str(exc))
            refresh_status()

        run_async(obj.abort_trial, on_success, on_error, busy_widgets=trial_buttons)

    def redo_trial():
        obj = session['obj']
        if obj is None:
            return
        if not messagebox.askyesno(
            'Redo trial',
            'DELETE the existing rosbag for this trial and clear its Excel row '
            '(Completed, bag path, and any outcome data -- contact force, '
            'completion time / dropped pegs, TLX-adjacent notes, etc.) so it '
            'can be re-recorded?'
        ):
            return
        try:
            obj.redo_trial()
            refresh_status()
        except Exception as exc:
            messagebox.showerror('Redo trial failed', str(exc))

    def next_trial():
        obj = session['obj']
        if obj is None:
            return
        info = obj.current()
        if info is not None and not info['done']:
            if not messagebox.askyesno('Next trial', 'This trial has not been recorded yet -- advance anyway?'):
                return
        else:
            if not messagebox.askyesno('Next trial', 'Move on to the next trial?'):
                return
        obj.advance()
        refresh_status()
        apply_current_mode()

    btn_start = ttk.Button(button_row, text='Start trial', command=start_trial)
    btn_stop = ttk.Button(button_row, text='Stop trial', command=stop_trial)
    btn_abort = ttk.Button(button_row, text='Abort (false start)', command=abort_trial)
    btn_redo = ttk.Button(button_row, text='Redo trial', command=redo_trial)
    btn_next = ttk.Button(button_row, text='Next trial →', command=next_trial)
    btn_start.pack(side='left', padx=3)
    btn_stop.pack(side='left', padx=3)
    btn_abort.pack(side='left', padx=3)
    btn_redo.pack(side='left', padx=3)
    btn_next.pack(side='left', padx=(15, 3))
    # disabled (all of them, to avoid overlapping actions) while stop_trial()/
    # abort_trial() are waiting in the background for `ros2 bag record` to
    # exit -- see run_async()
    trial_buttons = [btn_start, btn_stop, btn_abort, btn_redo, btn_next]

    ttk.Label(
        trial_frame,
        text=('Start trial restarts the video relay itself, fresh, for every trial (needed so '
              'theora/jpeg headers land inside that trial\'s own bag -- see VideoRelay docstring).\n'
              '(dvrk_video/gscam itself still needs to be started separately, by hand.)\n'
              'Close "Pilot_Study.xlsx" while running a session (see file header comment).'),
        foreground='gray', justify='left',
    ).pack(anchor='w', padx=5, pady=(0, 8))

    def on_close():
        relay.stop()
        root.destroy()

    root.protocol('WM_DELETE_WINDOW', on_close)
    root.mainloop()


