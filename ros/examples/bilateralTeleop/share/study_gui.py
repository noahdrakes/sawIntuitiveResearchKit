"""Mode/DO panel (same as teleop_gui.py) plus a pilot-study trial runner
driven by "Pilot_Study.xlsx" (pilot_data/, generated by build_workbook_v3.py):
auto mode-switching per trial,
start/stop/redo recordings, and on-screen tumor location / peg transfer
setup info so you can prep the physical task correctly before each trial.

Must be run FROM INSIDE the embedded IRE IPython shell (dvrk_system -e
IRE_IPYTHON), NOT as a separate process -- mtsManagerLocal.GetInstance()
only sees components living in its own process:

    %run study_gui.py
    # or: exec(open('study_gui.py').read())

Tkinter's mainloop runs in a background thread so the IPython prompt stays
usable while the window is open. `ros2 bag record` runs as its own OS
subprocess (non-blocking Popen), not a Python thread -- there is no polling
thread for it; Stop/Abort act on the Popen handle directly.

Close "Pilot_Study.xlsx" in Excel/LibreOffice before running a
session: this reads the trial plan once at session start and writes results
back after each trial, but a spreadsheet app with the file open doesn't see
those external writes and can silently overwrite them if you save there
mid-session. The GUI shows everything you need (mode, trial #, tumor
location / peg config) so you shouldn't need the sheet open at all while
running.
"""
