# raw is whatever dvrk_video's gscam launch publishes (started separately,
# by hand, same as always -- this GUI doesn't manage that process); the
# compressed topic only has data while the relay below is running, but it's
# safe to always list it in TOPICS regardless -- `ros2 bag record` just
# records nothing for a topic with no publisher, same as any other signal
# that happens to be inactive for a given trial
RAW_VIDEO_TOPIC = '/decklink/image_raw'
COMPRESSED_VIDEO_TOPIC = '/decklink/image_raw/compressed'
THEORA_VIDEO_TOPIC = '/decklink/image_raw/theora'

# image_transport plugin name -> (bag topic, ros2 run image_transport republish
# 2nd positional arg). Theora is an actual inter-frame video codec (exploits
# redundancy between frames, not just within one), so for a mostly-static
# surgical scene it compresses substantially smaller than JPEG-per-frame at
# comparable visual quality -- confirmed installed and registered
# (`ros2 run image_transport list_transports` lists `image_transport/theora`,
# provided by the `theora_image_transport` package). Kept jpeg as an option
# since it's the simpler/more universally-playable format if that ever matters
# more than size.
VIDEO_TRANSPORTS = {
    'theora (recommended)': ('theora', THEORA_VIDEO_TOPIC),
    'jpeg': ('compressed', COMPRESSED_VIDEO_TOPIC),
}
DEFAULT_VIDEO_TRANSPORT = 'theora (recommended)'

# theora's own header/setup packets (b_o_s=1) are only ever emitted ONCE, at
# encoder startup -- NOT resent to late subscribers (DDS durability on the
# topic is VOLATILE, confirmed live). A relay left running across multiple
# trials means only the FIRST trial recorded after it starts actually
# captures those header packets -- every trial after that has a theora
# stream with no headers at all, which no theora decoder (ROS or otherwise)
# can make sense of. Found this the hard way: P01_S2_BIL_T02/T04/UNI_T03 and
# a redone P01_S2_CSB_T01 all came back with first_packetno in the
# 3600-3700s and zero b_o_s packets -- their video tracks are unrecoverable
# (the one bag that did have the headers was overwritten by a same-stem
# redo), though the actual kinematic/force topics in those bags are
# untouched and fine.
#
# Fixed at the source, not worked around: TrialSession.start_trial() now
# restarts VideoRelay fresh for every trial (bag record first, then the
# relay restart, so the recorder's subscription is already live when the
# new encoder's headers go out -- see the comment in start_trial()).
# Verified for real: restarted the relay against the live feed and
# confirmed via `ros2 topic echo --field b_o_s` that the first packet after
# a restart is a real header packet, then recorded+decoded a test bag
# through the exact same ordering used here and it decoded clean. jpeg is
# kept as a fallback -- it has no bootstrapping requirement at all, so it's
# worth reaching for only if a session-specific issue ever breaks the
# restart-per-trial guarantee (e.g. RAW_VIDEO_TOPIC not up yet at trial
# start) and there's no time to debug it mid-session.

TOPICS = [
    '/PSM2/measured_js', '/PSM2/setpoint_js', '/PSM2/measured_cp', '/PSM2/measured_cv', '/PSM2/body/measured_cf',
    '/MTMR/measured_js', '/MTMR/setpoint_js', '/MTMR/measured_cp', '/MTMR/measured_cv', '/MTMR/body/measured_cf',
    '/measured_cf',
    # both listed regardless of which transport is actually running this
    # session -- `ros2 bag record` just records nothing for a topic with no
    # publisher, same as any other signal that happens to be inactive
    COMPRESSED_VIDEO_TOPIC,
    THEORA_VIDEO_TOPIC,
]

